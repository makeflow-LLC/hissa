import "server-only";

/**
 * فحص ملفّ PDF قبل إرساله إلى النموذج — على الخادم وحده.
 *
 * **لا نستخرج النصّ، والسبب عربيّ بحت.** المستخرِجات المبنيّة على pdf.js
 * تُعيد الحروف العربية بأشكال العرض (Arabic Presentation Forms) وبترتيب
 * بصريّ لا منطقيّ: «الدرس الثالث: قانون أوم» تخرج «أوم نﻮﻧﺎﻗ :ﺚﻟﺎﺜﻟا رسﺪﻟا».
 * وتوحيد NFKC يُصلح الأشكال ولا يُصلح الترتيب — وعكس السطر يُفسد ما كان
 * سليماً أصلاً («موأ» بدل «أوم»). فأي ملخّص يُبنى على هذا النصّ يكون
 * ملخّصاً لنصٍّ مشوّه، وهو أسوأ من غياب الميزة.
 *
 * لذلك يُرسَل الملفّ **كما هو** إلى النموذج فيقرأ صفحاته بنفسه — وقد
 * تحقّقنا أنه يقرأ الملفّ الممسوح ضوئياً كذلك، وهو أصعب الحالات.
 *
 * وظيفة هذه الوحدة إذن شيئان: التأكّد من أن الملفّ PDF سليم فعلاً، وعدّ
 * صفحاته لنرفض الكتاب الكامل قبل أن يُنفَق عليه شيء.
 */

/** أكثر من هذا ليس درساً بل كتاباً — والتكلفة تنمو مع الصفحات */
export const MAX_PDF_PAGES = 30;

export async function pdfPageCount(bytes: Uint8Array): Promise<number> {
  // استيراد كسول: pdf.js ثقيلة ولا تلزم إلا حين يرفع أحدهم ملفاً
  const { getDocumentProxy } = await import("unpdf");
  const pdf = await getDocumentProxy(bytes);
  return Math.max(1, pdf.numPages || 1);
}
