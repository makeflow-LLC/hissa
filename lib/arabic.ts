/**
 * تطبيع النص العربي للبحث.
 *
 * البحث الحرفي يفشل في العربية لأسباب يومية: الطالب يكتب «احمد» والاسم
 * مخزَّن «أحمد»، أو «رياضيه» و«رياضية»، أو ينسخ نصاً مشكّلاً. التطبيع
 * يوحّد هذه الصور قبل المقارنة على الطرفين.
 */

/** التشكيل والتطويل — تُحذف تماماً */
const DIACRITICS = /[ؐ-ًؚ-ٰٟۖ-ۭـ]/g;

/** الأرقام العربية-الهندية ← لاتينية، ليطابق «٥» الرقم 5 */
const ARABIC_DIGITS: Record<string, string> = {
  "٠": "0", "١": "1", "٢": "2", "٣": "3", "٤": "4",
  "٥": "5", "٦": "6", "٧": "7", "٨": "8", "٩": "9",
  "۰": "0", "۱": "1", "۲": "2", "۳": "3", "۴": "4",
  "۵": "5", "۶": "6", "۷": "7", "۸": "8", "۹": "9",
};

export function normalizeArabic(input: string): string {
  if (!input) return "";
  return input
    .normalize("NFKD")
    /**
     * كل العلامات المركّبة تُحذف بعد التفكيك.
     * لا يكفي نطاق التشكيل المعروف: NFKD يفكّك «إ» إلى ألف + همزة سفلية
     * (U+0655) وهي خارج ذلك النطاق، فكانت تتحوّل إلى مسافة — أي أن
     * «الإسلامية» تصير كلمتين ولا تطابق «اسلامية» أبداً.
     */
    .replace(/\p{M}+/gu, "")
    .replace(DIACRITICS, "")
    // صور الألف كلها ← ا
    .replace(/[إأآٱا]/g, "ا")
    // الألف المقصورة ← ياء، والهمزات المتطرفة ← حرفها الأصلي
    .replace(/ى/g, "ي")
    .replace(/[ؤئء]/g, "ي")
    // التاء المربوطة ← هاء (رياضية = رياضيه)
    .replace(/ة/g, "ه")
    .replace(/[٠-٩۰-۹]/g, (d) => ARABIC_DIGITS[d] ?? d)
    // الرموز والفواصل ← مسافة، ثم ضغط المسافات
    .replace(/[^\p{L}\p{N}]+/gu, " ")
    .trim()
    .toLowerCase();
}

/**
 * تطبيع اسم المادة للمقارنة وحدها — لا للبحث.
 *
 * يزيد على `normalizeArabic` إسقاطَ أداة التعريف، فـ«اللغة العربية»
 * و«لغة عربية» مادة واحدة. هذا ما يمنع الطالب من متابعة معلّمَي مادة
 * واحدة لمجرّد أن أحدهما كتبها معرّفة. يجب أن يطابق `normalize_ar`
 * في هجرة 0013 حرفاً بحرف، وإلا سمحت الواجهة بما ترفضه قاعدة البيانات.
 */
export function normalizeSubject(input: string): string {
  return normalizeArabic(input)
    .replace(/(^| )ال/g, "$1")
    .replace(/\s+/g, " ")
    .trim();
}

/**
 * هل يطابق النص كل كلمات الاستعلام؟
 * نطابق كل كلمة على حدة، فيجد «احمد رياضيات» المعلّم أحمد في مادة
 * الرياضيات حتى لو لم تتجاور الكلمتان في النص.
 */
export function matchesQuery(haystack: string, query: string): boolean {
  const q = normalizeArabic(query);
  if (!q) return true;
  const target = normalizeArabic(haystack);
  return q.split(" ").every((word) => target.includes(word));
}
