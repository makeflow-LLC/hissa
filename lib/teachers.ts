function attachments(lessonId: string, topic: string): Attachment[] {
  return [
    {
      id: `${lessonId}-summary`,
      name: `ملخص درس ${topic}`,
      kind: "pdf",
      size: "١٫١ م.ب",
      file: "/files/lesson-summary.pdf",
    },
    {
      id: `${lessonId}-worksheet`,
      name: `ورقة عمل ${topic}`,
      kind: "worksheet",
      size: "٦٥٠ ك.ب",
      file: "/files/worksheet.pdf",
    },
    {
      id: `${lessonId}-drills`,
      name: `تدريبات إضافية مع الإجابات`,
      kind: "pdf",
      size: "٨٩٠ ك.ب",
      file: "/files/extra-exercises.pdf",
    },
  ];
}

interface LessonDraft {
  id: string;
  title: string;
  description: string;
  duration: string;
  emoji: string;
  gradient: string;
  video: number;
  intro: string;
  explain: string[];
  apply: string;
  gallery: [string, string][];
}

function lesson(d: LessonDraft): RecordedLesson {
  return {
    id: d.id,
    title: d.title,
    description: d.description,
    duration: d.duration,
    emoji: d.emoji,
    gradient: d.gradient,
    videoUrl: SAMPLE_VIDEOS[d.video % SAMPLE_VIDEOS.length],
    sections: [
      { heading: "مقدمة الدرس", paragraphs: [d.intro] },
      { heading: "الشرح التفصيلي", paragraphs: d.explain },
      { heading: "التطبيق والملخص", paragraphs: [d.apply] },
    ],
    gallery: d.gallery.map(([emoji, caption], i) => ({
      id: `${d.id}-img-${i + 1}`,
      emoji,
      caption,
      gradient: GALLERY_GRADIENTS[i % GALLERY_GRADIENTS.length],
    })),
    attachments: attachments(d.id, d.title),
  };
}

