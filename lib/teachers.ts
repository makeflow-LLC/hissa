export const STAGES = ["ابتدائي", "إعدادي", "ثانوي"] as const;

export type Stage = (typeof STAGES)[number];

export interface ContentSection {
  heading: string;
  paragraphs: string[];
}

export interface GalleryItem {
  id: string;
  emoji: string;
  caption: string;
  gradient: string;
}

export interface Attachment {
  id: string;
  name: string;
  kind: "pdf" | "worksheet";
  size: string;
  file: string;
}

export interface RecordedLesson {
  id: string;
  title: string;
  description: string;
  duration: string;
  emoji: string;
  gradient: string;
  videoUrl: string;
  sections: ContentSection[];
  gallery: GalleryItem[];
  attachments: Attachment[];
}

export interface Unit {
  id: string;
  title: string;
  description: string;
  lessons: RecordedLesson[];
}

export interface LiveSession {
  id: string;
  title: string;
  description: string;
  schedule: string;
  duration: string;
  seatsLeft: number;
  emoji: string;
  gradient: string;
}

export interface Teacher {
  slug: string;
  name: string;
  subject: string;
  stage: Stage;
  bio: string;
  initials: string;
  gradient: string;
  rating: number;
  ratingCount: number;
  units: Unit[];
  liveSessions: LiveSession[];
}

