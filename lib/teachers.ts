export function getTeacherBySlug(slug: string): Teacher | undefined {
  return teachers.find((t) => t.slug === slug);
}

/** كل الدروس المسجّلة لمعلم ما بترتيب المنهج (وحدة بعد وحدة) */
export function getAllLessons(teacher: Teacher): { unit: Unit; lesson: RecordedLesson }[] {
  return teacher.units.flatMap((unit) =>
    unit.lessons.map((lesson) => ({ unit, lesson }))
  );
}

export interface LessonContext {
  teacher: Teacher;
  unit: Unit;
  lesson: RecordedLesson;
  index: number;
  total: number;
  prev: RecordedLesson | null;
  next: RecordedLesson | null;
}

export function getLessonContext(
  slug: string,
  lessonId: string
): LessonContext | undefined {
  const teacher = getTeacherBySlug(slug);
  if (!teacher) return undefined;
  const all = getAllLessons(teacher);
  const index = all.findIndex((e) => e.lesson.id === lessonId);
  if (index === -1) return undefined;
  return {
    teacher,
    unit: all[index].unit,
    lesson: all[index].lesson,
    index,
    total: all.length,
    prev: index > 0 ? all[index - 1].lesson : null,
    next: index < all.length - 1 ? all[index + 1].lesson : null,
  };
}
