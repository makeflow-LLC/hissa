-- درجاتٌ يصعدها الطالب، وكل درجة تحدٍّ من نوع آخر: اختيار، ثم حكمٌ على
-- جملة، ثم صورة، ثم ترتيب حروف، ثم كتابة الإجابة — والصعوبة تتدرّج مع
-- الارتفاع. ورتابة السؤال الواحد المكرّر هي ما يُنهي اللعب مبكّراً.
--
-- ولا عمود جديد لها: `items` هي `jsonb` نفسها، وإنّما اتّسع شكل العنصر
-- بحقل `img` اختياريّ. وهذا هو مكسب النموذج — اللعبة الحادية عشرة لا
-- تحتاج هجرةً إلا لتوسيع القيد.
--
-- والصور تُرفع إلى حاوية `lesson-media` داخل مجلد المعلّم (سياسة 0007
-- كما هي)، ويُتحقّق في الشيفرة أن الرابط داخل مضيف المشروع وحده — نفس
-- قاعدة `sanitizeLessonHtml`، فالرابط الخارجيّ في متصفّح الطالب منارةُ
-- تتبّع.

alter table public.activities drop constraint if exists activities_kind_check;
alter table public.activities
  add constraint activities_kind_check check (kind in (
    'match', 'flashcards', 'quiz', 'anagram', 'sort', 'wheel',
    'memory', 'truefalse', 'balloons', 'speed',
    'pyramid'
  ));
