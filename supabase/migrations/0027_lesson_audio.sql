-- ------------------------------------------------------------
-- 0027 — صوتُ الدرس
--
-- ملفٌّ واحد لكل درس، يُخزَّن رابطه فقط. الملفّ نفسه في حاوية
-- `lesson-media` تحت مجلّد المعلّم (سياسة 0007 نفسها) — ودقيقةُ صوتٍ
-- نحو ٢٫٧ ميغابايت، فوضعُها داخل الصفّ يعني قراءتها مع كل استعلام قائمة.
-- ------------------------------------------------------------

alter table public.lessons
  add column if not exists audio_url text;

/*
 * الصوت **محجوبٌ عن الزائر** كبقية محتوى الدرس.
 *
 * 0004 يحجب `sections` و`gallery` و`video_url` عن `anon` بمنحة أعمدة —
 * وRLS يرشّح الصفوف لا الأعمدة، فعمودٌ جديد يحمل محتوى الدرس يجب أن
 * يُحجب صراحةً وإلا صار بابَ تسريبٍ يلتفّ على البوّابة كلّها: يسمع
 * الزائر الدرس كاملاً وهو ممنوعٌ من قراءته.
 */
revoke select (audio_url) on public.lessons from anon;
