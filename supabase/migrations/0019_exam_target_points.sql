-- ============================================================
-- العلامة الكلّية المقصودة للاختبار
-- ============================================================
--
-- المعلّم يقرّر أوّلاً «الاختبار من ١٠»، ثم يوزّع العلامات على الأسئلة —
-- وقد ينسى سؤالاً أو يخطئ في الجمع فيخرج المجموع ٨. لا أحد يكتشف الفرق
-- إلا بعد أن يقدّم الطلاب.
--
-- العمود اختياري: من لا يريد سقفاً محدّداً يتركه فارغاً، فلا تحقّق ولا
-- تنبيه. ومجموع الأسئلة يبقى هو المصدر الوحيد للدرجة في التصحيح
-- (`grade_exam_attempt` يجمعه من `exam_questions` نفسها) — هذا العمود
-- **نيّةُ المعلّم لا حقيقةُ الاختبار**، وُجد ليُقارَن بها لا ليحلّ محلّها.

alter table public.exams
  add column if not exists target_points numeric(7, 2)
  check (target_points is null or target_points > 0);

comment on column public.exams.target_points is
  'العلامة الكلّية التي يقصدها المعلّم — تُقارَن بمجموع الأسئلة للتنبيه، ولا تُستخدم في التصحيح.';
