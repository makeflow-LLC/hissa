-- ------------------------------------------------------------
-- 0032 — وسيلة تواصلٍ مباشرة مع المعلّم قبل الحجز
--
-- الطالب قد يحتاج سؤالاً قبل أن يحجز: «هل تشرح هذا الدرس؟»، «هل يناسبك
-- وقتٌ آخر؟». وبلا وسيلةٍ للسؤال يحجز على الظنّ أو ينصرف.
--
-- **والرقم اختيارُ المعلّم لا قدرُه**: `contact_public` مفتاحٌ يملكه هو،
-- والواجهة لا تُظهر الرقم إلا **لمستخدمٍ مسجّل الدخول** — فالكاشط الذي
-- يجمع الأرقام لا يسجّل بحساب جوجل، والطالب الحقيقي مسجّلٌ أصلاً.
-- ------------------------------------------------------------

alter table public.teachers
  add column if not exists phone text;

/*
 * الافتراض `true` عن عمد: حقل الواتساب كان يَعِد صاحبه في الواجهة بأنه
 * «يظهر في بروفايلك»، فمن ملأه ملأه لينشره. والإخفاء الافتراضيّ كان
 * سيخالف ما قيل له لا العكس.
 */
alter table public.teachers
  add column if not exists contact_public boolean not null default true;

/*
 * **منحة الأعمدة إلزامية هنا.**
 *
 * 0026 أسقطت منحة UPDATE الشاملة على `teachers` وأعادتها عموداً عموداً
 * (بلا `credits`)، فالعمود الجديد **لا يقبل التعديل** حتى يُمنح صراحةً.
 * ونسيانُ هذا السطر لا يظهر في البناء ولا في الأنواع: يحفظ المعلّم
 * فيبتلع الحفظُ التغييرَ صامتاً.
 */
grant update (phone, contact_public) on public.teachers to authenticated;
grant select (phone, contact_public) on public.teachers to anon, authenticated;
